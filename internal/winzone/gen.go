//go:build ignore

// gen writes zones_gen.go from CLDR's windowsZones.xml: go run gen.go <xml>.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/xml"
	"fmt"
	"go/format"
	"os"
	"sort"
)

// known pins the SHA-256 of windowsZones.xml of each CLDR release the table
// may come from (raw.githubusercontent.com/unicode-org/cldr/release-N/
// common/supplemental/windowsZones.xml).
var known = map[string]string{
	"49": "5f902f94106a396cb7774f0b0e1ca4dfecb686494045350c0b4935d378e3913b",
}

type mapZone struct {
	Other     string `xml:"other,attr"`
	Territory string `xml:"territory,attr"`
	Type      string `xml:"type,attr"`
}

type doc struct {
	Zones []mapZone `xml:"windowsZones>mapTimezones>mapZone"`
}

func main() {
	if len(os.Args) != 2 {
		fail("usage: go run gen.go <windowsZones.xml>")
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fail(err.Error())
	}
	sum := sha256.Sum256(raw)
	hexSum := hex.EncodeToString(sum[:])
	version := ""
	for v, h := range known {
		if h == hexSum {
			version = v
		}
	}
	if version == "" {
		fail("sha256 " + hexSum + " is no known CLDR release: add it to known after checking the release")
	}
	var d doc
	if err := xml.Unmarshal(raw, &d); err != nil {
		fail(err.Error())
	}
	m := map[string]string{}
	for _, z := range d.Zones {
		if z.Territory == "001" {
			m[z.Other] = z.Type
		}
	}
	if len(m) < 130 {
		fail(fmt.Sprintf("only %d territory 001 zones: wrong file?", len(m)))
	}
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen.go from CLDR %s windowsZones.xml (sha256 %s); DO NOT EDIT.\n\n", version, hexSum)
	fmt.Fprintf(&b, "package winzone\n\n// CLDRVersion is the Unicode CLDR release the table comes from.\nconst CLDRVersion = %q\n\n", version)
	b.WriteString("// zones maps a Windows zone key to its primary (territory 001) IANA zone.\nvar zones = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, m[k])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail(err.Error())
	}
	if err := os.WriteFile("zones_gen.go", out, 0o644); err != nil {
		fail(err.Error())
	}
}

func fail(msg string) {
	fmt.Fprintln(os.Stderr, "gen:", msg)
	os.Exit(1)
}
